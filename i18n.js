let currentLanguage = 'en';
try {
  currentLanguage = localStorage.getItem('siteLanguage') === 'tr' ? 'tr' : 'en';
} catch (error) {
  currentLanguage = 'en';
}

function translate(key) {
  return translations[currentLanguage][key] || key;
}

function renderLanguage() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = translate(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(element => {
    element.setAttribute('aria-label', translate(element.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    element.alt = translate(element.dataset.i18nAlt);
  });
  document.querySelectorAll('[data-i18n-content]').forEach(element => {
    element.setAttribute('content', translate(element.dataset.i18nContent));
  });
  document.querySelectorAll('[data-lang]').forEach(button => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle('selected', active);
    button.setAttribute('aria-pressed', String(active));
  });
  window.dispatchEvent(new Event('languagechange'));
}

function setLanguage(language) {
  if (language !== 'en' && language !== 'tr') return;
  currentLanguage = language;
  try {
    localStorage.setItem('siteLanguage', language);
  } catch (error) {
    // The language selector still works when browser storage is unavailable.
  }
  renderLanguage();
}

window.t = translate;
window.getLanguage = () => currentLanguage;

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-lang]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });
  renderLanguage();
});
